import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source = fs.readFileSync(new URL('../public/scripts/pages/account-dashboard.js', import.meta.url), 'utf8');
const start = source.indexOf('function getRequestHeaderStatus(');
const end = source.indexOf('\n}', start) + 2;
const context = vm.createContext({});
vm.runInContext(source.slice(start, end), context);
const active = { status: 'active', label: 'Active' };
assert.equal(context.getRequestHeaderStatus({ verification_status: 'pending' }, active).label, 'Pending review');
assert.equal(context.getRequestHeaderStatus({ verification_status: 'verified', operational_status: 'approved' }, active).label, 'Approved');
assert.equal(context.getRequestHeaderStatus({ verification_status: 'needs_clarification' }, active).label, 'Needs clarification');
assert.equal(context.getRequestHeaderStatus({ verification_status: 'rejected' }, active).label, 'Not approved');
assert.equal(context.getRequestHeaderStatus({ operational_status: 'fulfilled' }, active).label, 'Fulfilled');
assert.equal(context.getRequestHeaderStatus({ operational_status: 'cancelled' }, active).label, 'Cancelled');
const card = source.slice(source.indexOf('function renderRequestCard('), source.indexOf('let pendingBloodReceipt'));
assert.equal((card.match(/class="feed-status-pill/g) || []).length, 1);
assert.match(card, /class="request-arrangement-text"/);
assert.match(card, /class="request-card-heading"/);
assert.doesNotMatch(card, /request-progress-summary|Reason for request|REPLACEMENT DONORS NEEDED/);
assert.doesNotMatch(card, /Mark Blood Received/);
assert.match(card, /Private request/);
assert.match(card, /BLOOD REQUEST/);
assert.match(card, /View Details/);
assert.doesNotMatch(card, /onclick="markBloodReceived\(/);
console.log('Request badge regression checks passed.');
